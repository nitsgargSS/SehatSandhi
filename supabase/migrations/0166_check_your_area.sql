-- Names differ in spacing and punctuation between sources ("Yamuna Nagar" in
-- service_areas, "Yamunanagar" in pincode_directory): compare squashed.
create or replace function sehat_squash(p text)
returns text language sql immutable as $$
  select regexp_replace(lower(coalesce(p, '')), '[^a-z0-9]', '', 'g');
$$;

create or replace function sehat_area_check(p_pin text)
returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare
  v_pin text := regexp_replace(coalesce(p_pin, ''), '\D', '', 'g');
  v_area text;
  v_district text;
  v_state text;
  v_live_pin boolean := false;
  v_pins text[];
  v_live_pins integer;
  v_residents bigint;
  v_census integer;
  v_patients integer;
  v_businesses integer;
begin
  -- 1–8 only: 9xxxxx is the Army Postal Service, not a place, and the India
  -- Post file carries a few stray 9-rows that would otherwise answer.
  if v_pin !~ '^[1-8][0-9]{5}$' then
    return jsonb_build_object('found', false, 'reason', 'invalid');
  end if;

  select sa.area_name, sa.district, sa.state, sa.is_active
    into v_area, v_district, v_state, v_live_pin
    from service_areas sa where sa.pin_code = v_pin limit 1;
  if v_district is null then
    select pd.district, pd.state into v_district, v_state
      from pincode_directory pd where pd.pin_code = v_pin;
  end if;
  if v_district is null then
    return jsonb_build_object('found', false, 'reason', 'unknown', 'pin_code', v_pin);
  end if;

  -- Every pincode we know of in this district, from both sources.
  select array_agg(distinct p) into v_pins from (
    select sa.pin_code as p from service_areas sa
     where sehat_squash(sa.district) = sehat_squash(v_district) and sehat_squash(sa.state) = sehat_squash(v_state)
    union
    select pd.pin_code from pincode_directory pd
     where sehat_squash(pd.district) = sehat_squash(v_district) and sehat_squash(pd.state) = sehat_squash(v_state)
  ) x;

  select count(*) filter (where sa.is_active), coalesce(sum(sa.population) filter (where sa.is_active), 0)
    into v_live_pins, v_residents
    from service_areas sa
   where sehat_squash(sa.district) = sehat_squash(v_district) and sehat_squash(sa.state) = sehat_squash(v_state);

  select dp.population into v_census from district_population dp
   where sehat_squash(dp.district) = sehat_squash(v_district) and sehat_squash(dp.state) = sehat_squash(v_state)
   limit 1;

  select count(*) into v_patients from patients pa where pa.pin_code = any(v_pins);
  select count(*) into v_businesses from businesses b
   where b.status = 'active' and (b.own_pin_code = any(v_pins) or b.pin_codes && v_pins);

  return jsonb_build_object(
    'found', true,
    'pin_code', v_pin,
    'area', v_area,
    'district', v_district,
    'state', v_state,
    'live', v_live_pins > 0,
    'live_pincodes', v_live_pins,
    'live_residents', nullif(v_residents, 0),
    'census_population', v_census,
    'census_source', case when v_census is not null then 'Census 2011' end,
    -- Only once they are big enough to mean something.
    'patients', case when v_patients >= 25 then v_patients end,
    'businesses', case when v_businesses >= 5 then v_businesses end
  );
end $$;

revoke all on function sehat_area_check(text) from public;
