-- ============================================================================
-- Sehatsandhi — "check your area": any pincode → district, population, live?
--
-- Run AFTER 0165. Safe to re-run.
--
-- The business page's coverage card lets a visitor type their pincode and see
-- their own area: the district and state, whether Sehatsandhi is live there,
-- how many people live in the district, and — once there is enough of it to
-- mean something — how many patients and businesses we already have there.
--
-- ── WHERE THE NUMBERS COME FROM ─────────────────────────────────────────────
-- • Area, district, state: service_areas for live pincodes, pincode_directory
--   (0110 — India Post's All India Pincode Directory via data.gov.in, ~19,300
--   pincodes) for the rest.
-- • Population: district_population below — Census of India 2011, district
--   totals (640 districts; from the Primary Census Abstract as published at
--   github.com/nishusharma1608/India-Census-2011-Analysis, cross-checked
--   against github.com/pigshell/india-census-2011 — identical figures).
--   Matched to pincode_directory's district names by name and state, plus
--   renames only (Gurugram = Gurgaon, Kalaburagi = Gulbarga, …). A district
--   carved out after 2011 is NOT given its parent's figure — it simply has
--   none, and the page says nothing rather than something wrong.
--   615 of 733 districts matched, covering 90% of pincodes. The page always
--   labels the figure "Census 2011".
-- • Patients and businesses: our own tables, counted, never listed — and only
--   returned once there are 25+ patients / 5+ businesses in the district, so a
--   small number never reads as failure.
-- ============================================================================

create table if not exists district_population (
  district text not null,
  state text not null,
  population integer not null check (population > 0),
  source text not null default 'Census 2011',
  primary key (district, state)
);

alter table district_population enable row level security;
drop policy if exists "anyone_reads_district_population" on district_population;
create policy "anyone_reads_district_population" on district_population for select using (true);
grant select on district_population to anon, authenticated;
revoke insert, update, delete on district_population from anon, authenticated;

