// Builds supabase/migrations/0208_lab_catalogue_and_package_templates.sql from
// supabase/seed/lab/catalogue_more.psv (tests) and package_templates.psv.
// Run: node scripts/lab/build-catalogue.mjs
// Fields column: "Name:unit;Name=Option/Option;…" — empty means a narrative
// report (Findings / Impression). No reference ranges: they depend on each
// lab's machine and kit, so the lab sets them.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const read = f => {
  const [head, ...rows] = readFileSync(join(root, 'supabase', 'seed', 'lab', f), 'utf8').split(/\r?\n/).filter(l => l.trim())
  const cols = head.split('|')
  return rows.map(l => { const c = l.split('|'); if (c.length !== cols.length) throw new Error(`${f}: ${l}`); return Object.fromEntries(cols.map((k, i) => [k, c[i].trim()])) })
}
const q = v => v === '' || v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`
const fields = (kind, s) => {
  if (!s) return [{ kind: 'long_text', name: 'Findings' }, { kind: 'long_text', name: 'Impression' }]
  return s.split(';').map(f => {
    if (f.includes('=')) { const [name, opts] = f.split('='); return { kind: 'select', name: name.trim(), options: opts.split('/').map(o => o.trim()) } }
    const [name, unit = ''] = f.split(':')
    return unit.trim() || /ratio|ph/i.test(name) ? { kind: 'number', name: name.trim(), unit: unit.trim() } : { kind: 'text', name: name.trim() }
  })
}
const tests = read('catalogue_more.psv')
const codes = new Set(tests.map(t => t.code))
if (codes.size !== tests.length) throw new Error('duplicate code')
const templates = read('package_templates.psv')

const out = [`-- 0208: a much fuller lab test list, and ready-made packages. GENERATED by
-- scripts/lab/build-catalogue.mjs from supabase/seed/lab/*.psv — edit those.
--
-- lab_catalogue (0168) had 57 tests; this adds ${tests.length} more — blood, hormones,
-- vitamins, infections, tumour markers, immunology, urine / stool, cultures,
-- cytology, X-rays by region, ultrasound, Doppler, CT, MRI, heart, lungs,
-- nerves and hearing. Prices are suggestions the lab changes; result fields
-- carry units but no reference ranges (they depend on the lab's machine and
-- kit, so each lab sets its own). A lab adds a test to its price list by
-- picking it (sehat_lab_import_catalogue) — never by typing its name.
--
-- lab_package_templates: common packages (Full Body, Diabetes, Thyroid, Fever,
-- …) as lists of catalogue codes. A lab starts a package from one in a tap,
-- adjusts the tests and the price, and saves it as its own (lab_packages).
`]
out.push(`insert into lab_catalogue (code, name, category, department, sample_type, report_kind, default_price, tat_hours, parameters, sort_order) values`)
out.push(tests.map((t, i) => `  (${q(t.code)}, ${q(t.name)}, ${q(t.category)}, ${q(t.department)}, ${q(t.sample)}, ${q(t.kind)}, ${Number(t.price)}, ${Number(t.tat)}, ${q(JSON.stringify(fields(t.kind, t.fields)))}::jsonb, ${1000 + i * 10})`).join(',\n'))
out.push(`on conflict (code) do nothing;
`)
out.push(`create table if not exists lab_package_templates (
  id          serial primary key,
  name        text not null unique,
  description text,
  codes       text[] not null,
  sort_order  integer not null default 0,
  is_active   boolean not null default true
);
alter table lab_package_templates enable row level security;
drop policy if exists lab_package_templates_read on lab_package_templates;
create policy lab_package_templates_read on lab_package_templates for select to authenticated using (true);
revoke all on lab_package_templates from anon;
`)
out.push(`insert into lab_package_templates (name, description, codes, sort_order) values`)
out.push(templates.map((t, i) => `  (${q(t.name)}, ${q(t.description)}, array[${t.codes.split(',').map(c => q(c.trim())).join(', ')}], ${(i + 1) * 10})`).join(',\n'))
out.push(`on conflict (name) do update set description = excluded.description, codes = excluded.codes, sort_order = excluded.sort_order;

-- Every code a template names must be in the catalogue.
do $$ declare bad text; begin
  select string_agg(c, ', ') into bad from lab_package_templates t, unnest(t.codes) c
   where not exists (select 1 from lab_catalogue x where x.code = c);
  if bad is not null then raise exception 'Template codes missing from lab_catalogue: %', bad; end if;
end $$;

notify pgrst, 'reload schema';
`)
writeFileSync(join(root, 'supabase', 'migrations', '0208_lab_catalogue_and_package_templates.sql'), out.join('\n'))
console.log(`wrote 0208: ${tests.length} tests, ${templates.length} templates`)
